# --- V8/V13: blame keyed by content hash (survives checkout/merge) -----------


class BlobBlame(Base):
    """Per-line authorship keyed by ``(workspace_id, content_hash)`` so blame
    follows the content across checkout and merge (V8; workspace-scoped in V13)."""

    __tablename__ = "blob_blame"
    __table_args__ = (PrimaryKeyConstraint("workspace_id", "content_hash"),)

    workspace_id: Mapped[int] = mapped_column(
        BigInt, autoincrement=False, server_default=text("1")
    )
    content_hash: Mapped[str] = mapped_column(Text)
    runs: Mapped[str] = mapped_column(Text, nullable=False)


